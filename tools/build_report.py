#!/usr/bin/env python3
"""Assemble the Automation Release Report HTML from lab evidence."""

from __future__ import annotations

import base64
import html
import sys
from pathlib import Path

LAB_ROOT = Path(__file__).resolve().parent.parent
EVIDENCE_DIR = LAB_ROOT / "evidence"

SQL_QUERY_PATH = LAB_ROOT / "queries" / "user_validation.sql"
SQL_RESULT_PATH = EVIDENCE_DIR / "sql_result.txt"
PR_PATH = EVIDENCE_DIR / "pull_request.md"
TICKET_PATH = EVIDENCE_DIR / "jira_ticket.md"
EOD_PATH = EVIDENCE_DIR / "EndOfDay_Report.md"
OUTPUT_PATH = EVIDENCE_DIR / "Automation_Release_Report.html"

SCREENSHOTS = [
    ("SQL validation", "sql_validation.png"),
    ("Playwright pass", "playwright_pass.png"),
    ("Ticket link", "jira_link.png"),
]

PLAYWRIGHT_RESULT_CANDIDATES = [
    EVIDENCE_DIR / "playwright_result.txt",
    LAB_ROOT / "automation_project" / "test-results" / "last-run.txt",
]


def read_text(path: Path, default: str = "") -> str:
    if path.is_file():
        return path.read_text(encoding="utf-8")
    return default


def embed_image(filename: str) -> tuple[str, str | None]:
    for directory in (EVIDENCE_DIR, LAB_ROOT):
        path = directory / filename
        if path.is_file():
            encoded = base64.b64encode(path.read_bytes()).decode("ascii")
            return filename, f"data:image/png;base64,{encoded}"
    return filename, None


def section(title: str, body_html: str) -> str:
    return f"<section><h2>{html.escape(title)}</h2>{body_html}</section>"


def pre_block(text: str) -> str:
    return f"<pre>{html.escape(text.strip())}</pre>" if text.strip() else "<p><em>Not available yet.</em></p>"


def main() -> int:
    warnings: list[str] = []

    sql_query = read_text(SQL_QUERY_PATH, "-- queries/user_validation.sql not found")
    sql_result = read_text(SQL_RESULT_PATH)
    if not sql_result:
        warnings.append("SQL evidence missing (run run_sql.py after completing the query).")

    pr_record = read_text(PR_PATH)
    if not pr_record:
        warnings.append("PR record missing (run create_pr_record.py).")

    ticket_record = read_text(TICKET_PATH)
    if not ticket_record:
        warnings.append("Ticket evidence missing (run link_ticket.py).")

    eod_report = read_text(EOD_PATH)
    if not eod_report:
        warnings.append("End-of-Day report missing (run generate_eod_report.py).")

    playwright_result = ""
    for candidate in PLAYWRIGHT_RESULT_CANDIDATES:
        if candidate.is_file():
            playwright_result = candidate.read_text(encoding="utf-8")
            break

    screenshot_sections: list[str] = []
    for label, filename in SCREENSHOTS:
        name, data_uri = embed_image(filename)
        if data_uri:
            screenshot_sections.append(
                f"<figure><figcaption>{html.escape(label)} ({html.escape(name)})</figcaption>"
                f'<img alt="{html.escape(label)}" src="{data_uri}" style="max-width:100%;border:1px solid #ccc;" /></figure>'
            )
        else:
            warnings.append(f"Screenshot not found: {filename}")
            screenshot_sections.append(
                f"<p><em>{html.escape(label)}: {html.escape(name)} not captured yet.</em></p>"
            )

    warning_html = ""
    if warnings:
        items = "".join(f"<li>{html.escape(item)}</li>" for item in warnings)
        warning_html = f"<div class='warn'><strong>Warnings</strong><ul>{items}</ul></div>"

    document = f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <title>Automation Release Report — LC4 Project</title>
  <style>
    body {{ font-family: system-ui, sans-serif; margin: 2rem; color: #1e293b; line-height: 1.5; }}
    h1 {{ color: #0f766e; }}
    h2 {{ border-bottom: 2px solid #99f6e4; padding-bottom: 0.25rem; margin-top: 2rem; }}
    pre {{ background: #f8fafc; border: 1px solid #e2e8f0; padding: 1rem; overflow-x: auto; }}
    figure {{ margin: 1rem 0; }}
    figcaption {{ font-weight: 600; margin-bottom: 0.5rem; }}
    .warn {{ background: #fff7ed; border: 1px solid #fdba74; padding: 1rem; margin-bottom: 1.5rem; }}
  </style>
</head>
<body>
  <h1>Automation Release Report</h1>
  <p>MindBridge LC4 Project — Account Update automation workflow evidence.</p>
  {warning_html}
  {section("Activity 1 — SQL validation", "<h3>Query</h3>" + pre_block(sql_query) + "<h3>Result</h3>" + pre_block(sql_result))}
  {section("Activity 2 — Playwright", pre_block(playwright_result) if playwright_result else "<p><em>Run the Playwright test and capture playwright_pass.png.</em></p>")}
  {section("Activity 3 — Version control traceability", "<h3>Pull request</h3>" + pre_block(pr_record) + "<h3>Ticket</h3>" + pre_block(ticket_record))}
  {section("Activity 4 — End-of-Day report", pre_block(eod_report))}
  {section("Screenshots", "".join(screenshot_sections))}
  <footer><p><small>Generated by tools/build_report.py — open in Chrome and use Print → Save as PDF if required.</small></p></footer>
</body>
</html>
"""

    EVIDENCE_DIR.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(document, encoding="utf-8")

    print(f"OK: Wrote evidence/Automation_Release_Report.html")
    for item in warnings:
        print(f"WARN: {item}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
